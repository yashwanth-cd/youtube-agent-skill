"""Voice a video's script and write the timing its scenes animate against.

Engines (video.json -> "voice"):
    {"engine": "kokoro", "voice": "am_michael", "speed": 1.0}   default - natural, Apache-2.0
    {"engine": "piper", "model": "en_US-norman-medium", "lengthScale": 0.95}   fallback

    python3 tools/tts.py videos/video-002-some-slug               # narration + Shorts hooks
    python3 tools/tts.py videos/video-002-some-slug --shorts-only # only the Shorts hooks

Reads   <video>/script.json, <video>/video.json
Writes  <video>/audio/vo/<scene>.mp3      one narration track per scene
        <video>/audio/shorts/<slug>.mp3   the new spoken first line of each Short
        <video>/src/timing.json           per-scene duration and per-line start/end, in frames
        <video>/src/voice.ts              imports for the audio above
        <video>/captions/narration.srt    the whole narration with absolute times (feeds
                                          /yt-chapters, /yt-edit and /yt-shorts)

Models come from tools/setup.sh (tools/.models/). Piper paths can be overridden with --piper / --model.
"""

import argparse
import json
import re
import subprocess
import tempfile
import wave
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

FPS = 30
TOOLS = Path(__file__).resolve().parent

LEAD_IN = 0.6      # silence before the first line of a scene
TITLE_HOLD = 1.4   # extra beat after a line keyed "title", so a title card can land
LINE_GAP = 0.6     # breath between lines
TAIL = 1.2         # silence after the last line of a scene


def synth(piper, model, text, length_scale):
    with tempfile.NamedTemporaryFile(suffix=".wav") as f:
        subprocess.run(
            [piper, "-m", model, "-f", f.name, "--length-scale", str(length_scale),
             "--sentence-silence", "0.28"],
            input=text.encode(), check=True, capture_output=True)
        with wave.open(f.name) as w:
            rate = w.getframerate()
            pcm = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16)
    # trim the model's own leading and trailing silence so our gaps are the only gaps
    loud = np.nonzero(np.abs(pcm) > 400)[0]
    if len(loud):
        pcm = pcm[max(0, loud[0] - int(0.03 * rate)): loud[-1] + int(0.08 * rate)]
    return pcm, rate


def trim(pcm, rate):
    # trim the model's own leading and trailing silence so our gaps are the only gaps
    loud = np.nonzero(np.abs(pcm) > 400)[0]
    if len(loud):
        pcm = pcm[max(0, loud[0] - int(0.03 * rate)): loud[-1] + int(0.08 * rate)]
    return pcm


_kokoro = None


def synth_kokoro(text, voice, speed):
    global _kokoro
    if _kokoro is None:
        from kokoro_onnx import Kokoro
        _kokoro = Kokoro(str(TOOLS / ".models" / "kokoro" / "model.onnx"), str(TOOLS / ".models" / "kokoro" / "voices.npz"))
    samples, rate = _kokoro.create(text, voice=voice, speed=speed, lang="en-us")
    pcm = (np.clip(samples, -1, 1) * 32767).astype(np.int16)
    return trim(pcm, rate), rate


def write_mp3(path, pcm, rate):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(suffix=".wav") as f:
        with wave.open(f.name, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(rate)
            w.writeframes(pcm.tobytes())
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", f.name, "-c:a", "libmp3lame", "-b:a", "96k", str(path)], check=True)


def srt_time(t):
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"


def ident(name):
    return re.sub(r"\W", "_", name)


def write_voice_ts(video, scenes, shorts):
    out = ["// Generated by tools/tts.py - do not edit by hand."]
    out += [f'import vo_{ident(s)} from "../audio/vo/{s}.mp3";' for s in scenes]
    out += [f'import short_{ident(s)} from "../audio/shorts/{s}.mp3";' for s in shorts]
    out += ["", "export const VOICE: Record<string, string> = {"]
    out += [f'  "{s}": vo_{ident(s)},' for s in scenes]
    out += ["};", "", "export const SHORT_VOICE: Record<string, string> = {"]
    out += [f'  "{s}": short_{ident(s)},' for s in shorts]
    out += ["};", ""]
    (video / "src" / "voice.ts").write_text("\n".join(out))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("video", type=Path, help="the video folder, e.g. videos/video-002-some-slug")
    ap.add_argument("--piper", default=str(TOOLS / ".venv" / "bin" / "piper"))
    ap.add_argument("--model")
    ap.add_argument("--length-scale", type=float)
    ap.add_argument("--shorts-only", action="store_true", help="keep the narration, re-voice only the Shorts hooks")
    args = ap.parse_args()

    video = args.video.resolve()
    meta = json.loads((video / "video.json").read_text())
    voice = meta.get("voice", {})
    engine = voice.get("engine", "kokoro")
    model = args.model or str(TOOLS / ".models" / f"{voice.get('model', 'en_US-norman-medium')}.onnx")
    length_scale = args.length_scale or voice.get("lengthScale", 0.95)
    if engine == "kokoro":
        say = lambda text: synth_kokoro(text, voice.get("voice", "am_michael"), voice.get("speed", 1.0))
    else:
        say = lambda text: synth(args.piper, model, text, length_scale)
    script = json.loads((video / "script.json").read_text())
    shorts = meta.get("shorts", [])
    timing_path = video / "src" / "timing.json"

    texts = [s["hook"] for s in shorts]
    if not args.shorts_only:
        texts += [line["text"] for scene in script["scenes"] for line in scene["lines"]]
    if engine == "kokoro":
        # one model in memory; it already uses every core
        voiced = {t: say(t) for t in dict.fromkeys(texts)}
    else:
        # one Piper process per line is slow to start, so voice every line up front in parallel
        with ThreadPoolExecutor(4) as pool:
            voiced = dict(zip(texts, pool.map(say, texts)))

    if args.shorts_only:
        timing = json.loads(timing_path.read_text())
    else:
        timing, srt, clock, cue = {"fps": FPS, "scenes": []}, [], 0.0, 1
        for scene in script["scenes"]:
            chunks, lines, t, rate = [], [], LEAD_IN, 22050
            for i, line in enumerate(scene["lines"]):
                pcm, rate = voiced[line["text"]]
                if i == 0:
                    chunks.append(np.zeros(int(LEAD_IN * rate), dtype=np.int16))
                dur = len(pcm) / rate
                lines.append({"key": line["key"], "text": line["text"],
                              "start": round(t * FPS), "end": round((t + dur) * FPS)})
                srt.append(f"{cue}\n{srt_time(clock + t)} --> {srt_time(clock + t + dur)}\n{line['text']}\n")
                cue += 1
                chunks.append(pcm)
                gap = LINE_GAP + (TITLE_HOLD if line["key"] == "title" else 0)
                gap = TAIL if i == len(scene["lines"]) - 1 else gap
                chunks.append(np.zeros(int(gap * rate), dtype=np.int16))
                t += dur + gap
            audio = np.concatenate(chunks)
            write_mp3(video / "audio" / "vo" / f"{scene['id']}.mp3", audio, rate)
            frames = int(np.ceil(len(audio) / rate * FPS))
            timing["scenes"].append({"id": scene["id"], "chapter": scene["chapter"],
                                     "durationInFrames": frames, "lines": lines})
            clock += frames / FPS
            print(f"{scene['id']:10} {frames / FPS:6.1f}s")
        (video / "captions").mkdir(exist_ok=True)
        (video / "captions" / "narration.srt").write_text("\n".join(srt))
        print(f"total      {clock:6.1f}s  ({int(clock // 60)}:{int(clock % 60):02})")

    timing["shorts"] = {}
    for s in shorts:
        pcm, rate = voiced[s["hook"]]
        pcm = np.concatenate([pcm, np.zeros(int(0.35 * rate), dtype=np.int16)])
        write_mp3(video / "audio" / "shorts" / f"{s['slug']}.mp3", pcm, rate)
        timing["shorts"][s["slug"]] = {"text": s["hook"], "durationInFrames": int(np.ceil(len(pcm) / rate * FPS))}
        print(f"short {s['n']}  {s['slug']:24} hook {len(pcm) / rate:4.1f}s")

    timing_path.write_text(json.dumps(timing, indent=1))
    write_voice_ts(video, [s["id"] for s in timing["scenes"]], [s["slug"] for s in shorts])


if __name__ == "__main__":
    main()
