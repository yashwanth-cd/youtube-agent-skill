// Rebuild VIDEOS.md, the channel's index, from every videos/*/video.json.
//   npm run index
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const rows = fs
  .readdirSync(path.join(root, "videos"))
  .filter((d) => fs.existsSync(path.join(root, "videos", d, "video.json")))
  .sort()
  .map((d) => {
    const m = JSON.parse(fs.readFileSync(path.join(root, "videos", d, "video.json"), "utf8"));
    const yt = m.youtube?.url ? `[watch](${m.youtube.url})` : "-";
    const shorts = (m.shorts ?? []).length;
    return `| ${String(m.number).padStart(3, "0")} | [${m.title}](videos/${d}/) | ${m.status} | ${m.runtime ?? "-"} | ${shorts} | ${m.youtube?.published ?? "-"} | ${yt} |`;
  });
const md = `# The Stickman Show — every video

Generated by \`npm run index\` from each \`videos/*/video.json\`. Do not edit by hand.

| # | video | status | runtime | shorts | published | YouTube |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}
`;
fs.writeFileSync(path.join(root, "VIDEOS.md"), md);
console.log(`VIDEOS.md: ${rows.length} video(s)`);
