"""Paint a background for every scene of a video with WanGP, on a machine with a GPU.

Run it with WanGP's own Python (the environment WanGP is installed in), from the stickman-show
folder:

    python tools/wangp_assets.py videos/video-002-rich-dad-poor-dad --wangp C:/WanGP
    python tools/wangp_assets.py videos/video-002-rich-dad-poor-dad --wangp C:/WanGP --only hook,dads --force

For each scene it uses the scene's "bg" prompt from script.json (or a default for its "set"),
wrapped in the channel's background style. Images land in <video>/assets/bg-<scene>.png
(1920x1080) and src/assets.ts is rewritten so the engine picks them up. Scenes without an image
keep the drawn set. Re-run with --force to repaint.

Model: Qwen-Image 20B (Apache-2.0, fine for a monetised channel). Pick another with --model only
after checking its licence; several image models (e.g. FLUX.1 dev) are non-commercial.
Uses WanGP (https://github.com/deepbeepmeep/Wan2GP); its terms ask integrations to say so.
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

STYLE = (
    "Flat vector illustration background for a 2D animated explainer video. {subject}. "
    "Eye-level view, the floor fills the bottom quarter of the frame, a calm open empty area in the "
    "middle and right of the frame for characters and graphics, soft warm colours, clean simple "
    "shapes, gentle depth, no people, no animals, no text, no letters, no logos. 16:9 widescreen."
)

SET_PROMPTS = {
    "room": "a cosy living room with a window on the left, a sofa, a floor lamp and plants, warm afternoon light",
    "kitchen": "a bright modern kitchen with mint green cabinets, a window and plants",
    "office": "a friendly modern office with a big window over a city skyline, bookshelves and plants",
    "street": "a city street with colourful buildings, a pavement and a street lamp, sunny day",
    "park": "a sunny park with rolling green hills, trees and a path",
    "bank": "the grand hall of a classic bank with marble columns",
    "board": "a classroom wall with a large empty whiteboard",
    "stage": "an empty theatre stage at night with a single spotlight and a dark blue curtain",
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("video", type=Path)
    ap.add_argument("--wangp", type=Path, required=True, help="the WanGP installation folder")
    ap.add_argument("--model", default="qwen_image_20B", help="a WanGP model type (defaults/<name>.json)")
    ap.add_argument("--resolution", default="1664x928")
    ap.add_argument("--steps", type=int, help="override the model's default number of steps")
    ap.add_argument("--only", help="comma-separated scene ids")
    ap.add_argument("--force", action="store_true", help="repaint scenes that already have an image")
    ap.add_argument("--profile", default="4", help="WanGP memory profile (see WanGP docs)")
    args = ap.parse_args()

    video = args.video.resolve()
    script = json.loads((video / "script.json").read_text())
    assets = video / "assets"
    assets.mkdir(exist_ok=True)
    only = set(args.only.split(",")) if args.only else None

    sys.path.insert(0, str(args.wangp.resolve()))
    from shared.api import init  # WanGP's in-process API (docs/API.md)

    session = init(root=args.wangp.resolve(), cli_args=["--attention", "sdpa", "--profile", args.profile])
    defaults = session.get_default_settings(args.model)

    for scene in script["scenes"]:
        sid = scene["id"]
        out = assets / f"bg-{sid}.png"
        if (only and sid not in only) or (out.exists() and not args.force):
            continue
        subject = scene.get("bg") or SET_PROMPTS.get(scene.get("set", ""), SET_PROMPTS["room"])
        settings = {**defaults, "model_type": args.model, "prompt": STYLE.format(subject=subject), "resolution": args.resolution, "batch_size": 1}
        if args.steps:
            settings["num_inference_steps"] = args.steps
        print(f"{sid}: painting '{subject}'")
        result = session.submit_task(settings).result()
        if not result.success:
            for e in result.errors:
                print(f"  error: {e.message}")
            continue
        produced = Path(result.generated_files[0])
        try:
            from PIL import Image

            Image.open(produced).convert("RGB").resize((1920, 1080), Image.LANCZOS).save(out)
        except ImportError:
            shutil.copy(produced, out)
        print(f"  -> {out.relative_to(video)}")

    write_assets_ts(video)


def write_assets_ts(video):
    files = sorted((video / "assets").glob("bg-*.png"))
    lines = ["// Generated by tools/wangp_assets.py - painted backgrounds per scene id."]
    for f in files:
        ident = "bg_" + f.stem[3:].replace("-", "_")
        lines.append(f'import {ident} from "../assets/{f.name}";')
    lines.append("")
    lines.append("export const BACKGROUNDS: Record<string, string> = {")
    for f in files:
        lines.append(f'  "{f.stem[3:]}": bg_{f.stem[3:].replace("-", "_")},')
    lines.append("};")
    (video / "src" / "assets.ts").write_text("\n".join(lines) + "\n")
    print(f"src/assets.ts: {len(files)} background(s)")


if __name__ == "__main__":
    main()
