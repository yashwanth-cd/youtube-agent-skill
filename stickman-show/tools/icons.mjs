//   npm run icons -- search money bank     # find icon names
//   npm run icons -- sync                  # bundle the icons every script uses (make/check run this)
// Only icons that are used get copied into src/engine/icons.generated.ts, so renders stay fast.
import { getIconData, iconToSVG } from "@iconify/utils";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = require("@iconify-json/fluent-emoji-flat/icons.json");
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
export const ICON_NAMES = Object.keys(set.icons).concat(Object.keys(set.aliases ?? {}));

/** Every string under an "icon" key (or in an "icons" list) anywhere in the scripts. */
const usedIn = (node, out) => {
  if (Array.isArray(node)) node.forEach((n) => usedIn(n, out));
  else if (node && typeof node === "object") {
    for (const [k, v] of Object.entries(node)) {
      if ((k === "icon" || k === "holding") && typeof v === "string") {
        if (v) out.add(v);
      }
      else if (k === "icons" && Array.isArray(v)) v.filter((x) => typeof x === "string").forEach((x) => out.add(x));
      else usedIn(v, out);
    }
  }
  return out;
};

export const sync = () => {
  const names = new Set(fs.readFileSync(path.join(root, "tools", "icons-base.txt"), "utf8").split(/\s+/).filter(Boolean));
  const videos = path.join(root, "videos");
  for (const d of fs.readdirSync(videos)) {
    for (const f of ["script.json", "video.json"]) {
      const p = path.join(videos, d, f);
      if (fs.existsSync(p)) usedIn(JSON.parse(fs.readFileSync(p, "utf8")), names);
    }
  }
  const missing = [];
  const out = {};
  for (const n of [...names].sort()) {
    const data = getIconData(set, n);
    if (!data) {
      missing.push(n);
      continue;
    }
    const svg = iconToSVG(data);
    out[n] = { body: svg.body, box: svg.attributes.viewBox };
  }
  const file = path.join(root, "src", "engine", "icons.generated.ts");
  fs.writeFileSync(
    file,
    `// Generated by tools/icons.mjs from Fluent Emoji (flat), MIT licence - do not edit.\n` +
      `export const ICONS: Record<string, { body: string; box: string }> = ${JSON.stringify(out)};\n`,
  );
  return { count: Object.keys(out).length, missing };
};

export const search = (words) =>
  ICON_NAMES.filter((n) => words.every((w) => n.includes(w.toLowerCase())) && !/-(light|medium|dark|medium-light|medium-dark)$/.test(n));

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const [cmd, ...rest] = process.argv.slice(2);
  if (cmd === "search") console.log(search(rest).slice(0, 80).join("  ") || "(no match - try a shorter word)");
  else if (cmd === "sync") {
    const r = sync();
    console.log(`${r.count} icons bundled`);
    if (r.missing.length) {
      console.log(`unknown icon names: ${r.missing.join(", ")}`);
      process.exit(1);
    }
  } else console.log("usage: npm run icons -- search <word...> | sync");
}
